// GovPrompt Thailand v7.1 — Government Prompt Quality Standard
// Additive quality layer: does not replace the existing 222-prompt catalogue.

export const GOVPROMPT_STANDARD_VERSION = "7.1.0";

export const DECISION_STATUSES = Object.freeze({
  YES: "ได้",
  NO: "ไม่ได้",
  CONDITIONAL: "ได้โดยมีเงื่อนไข",
  INSUFFICIENT: "หลักฐานยังไม่พอที่จะฟันธง"
});

export const EVIDENCE_HIERARCHY = Object.freeze([
  "กฎหมาย กฎ ระเบียบ ประกาศ หรือหลักเกณฑ์ต้นฉบับที่มีผลใช้บังคับ",
  "หน่วยงานเจ้าของเรื่อง/หน่วยงานผู้ออกหลักเกณฑ์",
  "หนังสือสั่งการ หนังสือซักซ้อม หรือแนวทางราชการ",
  "คำวินิจฉัย คำพิพากษา หรือมติที่เกี่ยวข้องและยังใช้ได้",
  "เว็บไซต์ราชการอื่น",
  "แหล่งสรุปหรือแหล่งรอง — ใช้ประกอบเท่านั้น ไม่ใช้แทนต้นฉบับเมื่อมีต้นฉบับ"
]);

const HIGH_RISK = /(เบิก|จ่าย|เงิน|โบนัส|ค่าตอบแทน|งบประมาณ|พัสดุ|จัดซื้อ|จัดจ้าง|TOR|ราคากลาง|สัญญา|ตรวจรับ|วินัย|ลงโทษ|อุทธรณ์|บุคคล|บรรจุ|แต่งตั้ง|เลื่อนเงินเดือน|สิทธิ|อำนาจ|อนุมัติ|กฎหมาย|ระเบียบ|ประกาศ|คำสั่ง|คดี|ฟ้อง|รพ\.สต|เงินบำรุง)/i;
const MEDIUM_RISK = /(ขั้นตอน|หนังสือราชการ|โครงการ|แผน|ประชุม|มอบอำนาจ|แนวทางปฏิบัติ)/i;
const DECISION_QUERY = /(ได้ไหม|ได้หรือไม่|มีสิทธิ|ไม่มีสิทธิ|ทำได้ไหม|ทำได้หรือไม่|เบิกได้|จ่ายได้|อนุมัติได้|ถูกไหม|ชอบด้วย|ต้องทำ|สามารถ)/i;

export function classifyRisk(question = "") {
  const q = String(question);
  if (HIGH_RISK.test(q)) return "HIGH";
  if (MEDIUM_RISK.test(q)) return "MEDIUM";
  return "LOW";
}

export function requiresDecisionGate(question = "") {
  return DECISION_QUERY.test(String(question));
}

export function buildQualityGate({ question = "", risk } = {}) {
  const level = risk || classifyRisk(question);
  const decision = requiresDecisionGate(question);
  const lines = [
    "มาตรฐานควบคุมคุณภาพ GovPrompt v7.1",
    `ระดับความเสี่ยง: ${level}`,
    "",
    "กฎบังคับก่อนตอบ",
    "1) แยกข้อเท็จจริงที่ผู้ใช้ให้ ออกจากข้อกฎหมาย/หลักเกณฑ์ และห้ามเติมข้อเท็จจริงเอง",
    "2) หากสิทธิ อำนาจ การเบิกจ่าย หรือผลทางราชการขึ้นกับหลายเงื่อนไข ต้องตรวจเงื่อนไขสาระสำคัญให้ครบ ห้ามสรุปจากเงื่อนไขเดียว",
    "3) ก่อนอ้างกฎหมาย ระเบียบ ประกาศ หลักเกณฑ์ หนังสือสั่งการ หรือแนววินิจฉัย ต้องตรวจฉบับที่มีผลกับช่วงเวลาของข้อเท็จจริง รวมการแก้ไข ยกเลิก และบทเฉพาะกาล",
    "4) ถ้าพบเอกสารเก่าและใหม่ขัดกัน ให้ตรวจสถานะการใช้บังคับและให้น้ำหนักต้นฉบับที่มีผลใช้บังคับก่อน",
    "5) ห้ามสมมติเลขมาตรา เลขข้อ เลขหนังสือ วันที่ มติ คำพิพากษา ชื่อบุคคล หรือแหล่งอ้างอิง",
    "6) หากตรวจความเป็นปัจจุบันไม่ได้หรือหลักฐานไม่พอ ให้ระบุชัดว่า 'หลักฐานยังไม่พอที่จะฟันธง' และบอกข้อมูล/เอกสารที่ขาด",
    "7) ใช้แหล่งราชการต้นฉบับก่อนแหล่งสรุป และอ้างเฉพาะแหล่งที่สนับสนุนข้อสรุปจริง",
    "8) คำนึงถึง PDPA และไม่ขอ/แสดงข้อมูลส่วนบุคคลที่ไม่จำเป็น",
    "9) ก่อนส่งคำตอบ ตรวจซ้ำว่าข้อสรุปสอดคล้องกับข้อเท็จจริง ฐานอำนาจ เงื่อนไข ข้อยกเว้น และช่วงเวลาที่ใช้บังคับ",
  ];

  if (level === "HIGH") {
    lines.push(
      "",
      "HIGH-RISK GATE",
      "- ต้องตรวจ Official Source + Freshness/Effective Date + Multi-condition ก่อนฟันธง",
      "- หากมีเครื่องมือค้นเว็บ ให้ค้นต้นฉบับราชการเมื่อคำตอบขึ้นกับข้อมูลปัจจุบัน",
      "- หากไม่มีเครื่องมือหรือยังยืนยันฉบับล่าสุดไม่ได้ ห้ามตอบแบบยืนยันเด็ดขาด",
      "- แยกผลเป็น: ข้อเท็จจริง / ฐานอำนาจ / วิเคราะห์เงื่อนไข / ความเสี่ยง / ข้อสรุป"
    );
  }

  if (decision) {
    lines.push(
      "",
      "DECISION GATE",
      "- ใช้ข้อสรุปหนึ่งใน 4 สถานะเท่านั้น: ได้ / ไม่ได้ / ได้โดยมีเงื่อนไข / หลักฐานยังไม่พอที่จะฟันธง",
      "- ห้ามใช้คำว่า 'มีสิทธิ', 'เบิกได้', 'จ่ายได้', 'ทำได้' หรือคำยืนยันเทียบเท่า จนตรวจเงื่อนไขจำเป็นครบ",
      "- ถ้าผ่านเพียงบางเงื่อนไข ให้บอกว่า 'ผ่านเฉพาะเงื่อนไข...' ไม่ใช่ 'ผ่านทั้งหมด'"
    );
  }

  lines.push(
    "",
    "ลำดับน้ำหนักหลักฐาน",
    ...EVIDENCE_HIERARCHY.map((item, i) => `${i + 1}. ${item}`),
    "",
    "รูปแบบคำตอบมาตรฐาน",
    "- Answer First: ข้อสรุปที่ใช้ตัดสินใจได้ก่อน",
    "- ฐานอำนาจ/หลักฐาน",
    "- วิเคราะห์ข้อเท็จจริงเทียบทุกเงื่อนไขที่มีสาระสำคัญ",
    "- ข้อยกเว้น/ความเสี่ยง/สิ่งที่ยังไม่ยืนยัน",
    "- ขั้นตอนถัดไปเฉพาะที่จำเป็น"
  );

  return lines.join("\n");
}

export function applyPromptStandard(basePrompt, options = {}) {
  const gate = buildQualityGate(options);
  return `${String(basePrompt || "").trim()}\n\n${gate}`.trim();
}
